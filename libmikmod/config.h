/* config.h - hand-written for the AMIX (Commodore Amiga UNIX, m68k SVR4)
   port. libmikmod's shipped autoconf/automake/libtool build system does not
   run on this target (no autotools on AMIX, and libtool has no knowledge of
   the m68k-cbm-sysv4 host), so this file is maintained by hand instead of
   being generated by ./configure. See usr/local/src/libmikmod/Makefile.

   Only the drivers actually compiled in (drv_nos, drv_raw, drv_wav,
   drv_stdout, drv_pipe, drv_amix) are enabled below; the rest of the
   drivers/drv_*.c files still compile fine even when disabled here, since
   each one falls back to a MISSING() stub when its DRV_ macro isn't
   defined. */

/* ---- Audio drivers compiled in ---- */
#define DRV_AMIX 1
#define DRV_PAULA 1
#define DRV_RAW 1
#define DRV_WAV 1
#define DRV_STDOUT 1
#define DRV_PIPE 1

/* ---- Headers available on AMIX (usr/include) ---- */
#define HAVE_FCNTL_H 1
#define HAVE_LIMITS_H 1
#define HAVE_MALLOC_H 1
#define HAVE_MEMORY_H 1
#define HAVE_STDLIB_H 1
#define HAVE_STRING_H 1
#define HAVE_SYS_IOCTL_H 1
#define HAVE_SYS_STAT_H 1
#define HAVE_SYS_TYPES_H 1
#define HAVE_SYS_WAIT_H 1
#define HAVE_UNISTD_H 1

/* Headers NOT present on AMIX -- left undefined:
   HAVE_STRINGS_H, HAVE_INTTYPES_H, HAVE_STDINT_H, HAVE_DLFCN_H,
   HAVE_DL_H, and every non-AMIX audio-device header
   (HAVE_SUN_AUDIOIO_H, HAVE_SYS_AUDIOIO_H, HAVE_SYS_SOUNDCARD_H, ...) */

/* ANSI C headers all present */
#define STDC_HEADERS 1

/* No srandom/setenv/snprintf on AMIX's SVR4 libc -- leave HAVE_SRANDOM,
   HAVE_SETENV, HAVE_SNPRINTF undefined; the few call sites in loaders/
   already fall back to rand()/sprintf() when these are undefined. */

/* No pthreads -- single-threaded build. MUTEX_LOCK/MUTEX_UNLOCK in
   mikmod_internals.h become no-ops when HAVE_PTHREAD is undefined. */

/* m68k is big-endian */
#define WORDS_BIGENDIAN 1

/* Package metadata (normally filled in by AC_INIT/AM_INIT_AUTOMAKE) */
#define PACKAGE "libmikmod"
#define PACKAGE_NAME "libmikmod"
#define PACKAGE_TARNAME "libmikmod"
#define PACKAGE_VERSION "3.1.23"
#define PACKAGE_STRING "libmikmod 3.1.23"
#define PACKAGE_BUGREPORT ""
#define PACKAGE_URL ""
#define VERSION "3.1.23"
