#!/usr/bin/env python3
"""kmap2xmodmap.py KMAP [NAME] -- turn an AMIX (Amiga UNIX) console keymap
(/usr/amiga/lib/kmap/*) into an xmodmap table for the Xzz9000 server, whose
built-in keymap is US only.  With -t, print the decoded table instead.

The X keycode is the Amiga raw code + 1 (MIN_AMIX_KEY in hw/amix/amixKeyMap.c).
Columns: plain, Shift, Alt, Alt+Shift.  The right Alt key becomes Mode_switch
(mod3) for the Alt column; the left Alt stays Alt (Motif mnemonics, dtwm).
X11R6.3 has no compose in the C locale, so dead keys become their spacing
characters (acute, grave, asciicircum, asciitilde, diaeresis).

Layout, read off the files themselves:
  0x00      "*K" magic, then the modifier-key table
  0x48+4*n  entry for Amiga raw key n:
              70 00 00 00  no key
              00 00 00 cc  one character for every modifier state
              50 0s 00 00  a dead key: sets dead state s
              60 oo oo oo  offset of [template][value per template word ...]
  template  words [?][dead state][modifiers][0x08 Ctrl], ending with the
            plain word 00 00 00 00; values are in the same order.  Modifier
            bits: 0x01 or 0x08 Shift (0x08 on letters, Caps Lock follows it),
            0x02 Alt.  A value of type 60 is a nested [template][values] block
            (the dead-key compositions); its no-dead-key entry is the character.
Dead states seen: 01 acute, 02 grave, 03/04 circumflex, 08 tilde, 10 diaeresis.
"""
import struct, sys
args = [a for a in sys.argv[1:] if a != '-t']
d = open(args[0], 'rb').read()
def w(o): return struct.unpack('>I', d[o:o+4])[0]
def block(o):
    """{(shift, alt): value} for the [template][values] block at offset o"""
    tmpl = w(o) & 0xffffff
    m = {}
    i = 0
    while True:
        word = w(tmpl + 4*i); v = w(o + 4 + 4*i); i += 1
        dead = (word >> 16) & 0xff; mods = (word >> 8) & 0xff; ctrl = word & 0xff
        if not dead and not ctrl:
            m.setdefault((bool(mods & 0x09), bool(mods & 0x02)), val(v))
        if word == 0:
            return m
def val(v):
    t = v >> 24
    if t == 0x00: return v & 0xff
    if t == 0x50: return 'dead:%x' % ((v >> 16) & 0xff)
    if t == 0x60: return block(v & 0xffffff).get((False, False))
    if t == 0x70: return None
    return 'type%x' % t
def decode(path=None):
    out = {}
    for raw in range(0x68):
        e = w(0x48 + 4*raw)
        t = e >> 24
        if t == 0x70: continue
        if t in (0x00, 0x50):
            v = val(e); out[raw] = {'plain': v, 'shift': v}; continue
        if t != 0x60: continue
        b = block(e & 0xffffff)
        out[raw] = {'plain': b.get((False, False)), 'shift': b.get((True, False)),
                    'alt': b.get((False, True)), 'altshift': b.get((True, True))}
    return out
out = decode()
def show(v):
    if v is None: return '-'
    if isinstance(v, str): return v
    return repr(chr(v)) if 32 <= v < 127 or v >= 0xa0 else '0x%02x' % v

NAMES = {' ': 'space', '!': 'exclam', '"': 'quotedbl', '#': 'numbersign', '$': 'dollar',
    '%': 'percent', '&': 'ampersand', "'": 'apostrophe', '(': 'parenleft', ')': 'parenright',
    '*': 'asterisk', '+': 'plus', ',': 'comma', '-': 'minus', '.': 'period', '/': 'slash',
    ':': 'colon', ';': 'semicolon', '<': 'less', '=': 'equal', '>': 'greater', '?': 'question',
    '@': 'at', '[': 'bracketleft', '\\': 'backslash', ']': 'bracketright', '^': 'asciicircum',
    '_': 'underscore', '`': 'grave', '{': 'braceleft', '|': 'bar', '}': 'braceright', '~': 'asciitilde'}
DEAD = {1: 'acute', 2: 'grave', 3: 'asciicircum', 4: 'asciicircum', 8: 'asciitilde', 0x10: 'diaeresis'}
LATIN1 = {0xb4: 'acute', 0xa8: 'diaeresis', 0xa0: 'nobreakspace'}

def keysym(v):
    if v is None: return 'NoSymbol'
    if isinstance(v, str):
        if v.startswith('dead:'): return DEAD.get(int(v[5:], 16), 'NoSymbol')
        return 'NoSymbol'
    c = chr(v)
    if c.isalnum() and v < 0x80: return c
    if c in NAMES: return NAMES[c]
    if v >= 0xa0: return LATIN1.get(v, '0x%04x' % v)
    return 'NoSymbol'

# the typing keys; keypad, cursor and function keys keep the server's keysyms
KEYS = list(range(0x00, 0x0e)) + list(range(0x10, 0x1c)) + list(range(0x20, 0x2c)) + \
       list(range(0x30, 0x3b)) + [0x40]

if '-t' in sys.argv:
    for raw in sorted(out):
        m = out[raw]
        print('%02x %-8s %-8s %-8s %-8s' % (raw, show(m.get('plain')), show(m.get('shift')),
              show(m.get('alt')), show(m.get('altshift'))))
    sys.exit(0)

name = args[1] if len(args) > 1 else args[0].split('/')[-1]
print('! xmodmap.amiga-%s -- the AMIX console keymap "%s" for the Xzz9000 server' % (name, name))
print('! generated by kmap2xmodmap.py from /usr/amiga/lib/kmap/%s; keycode = Amiga raw + 1' % name)
print('! right Alt = Mode_switch (the keymap\'s Alt column), left Alt stays Alt')
# set the modifiers outright, so loading the table twice is harmless
# (a "remove mod1 = Alt_R" fails once Alt_R is gone)
print('clear mod1')
print('clear mod3')
print('keycode 0x66 = Mode_switch')
print('add mod1 = Alt_L')
print('add mod3 = Mode_switch')
for raw in KEYS:
    m = out.get(raw)
    if not m or m.get('plain') is None: continue
    cols = [keysym(m.get(k)) for k in ('plain', 'shift', 'alt', 'altshift')]
    if cols[1] == 'NoSymbol' and len(cols[0]) == 1 and cols[0].isalpha():
        cols[1] = cols[0].upper()
    while cols and cols[-1] == 'NoSymbol': cols.pop()
    print('keycode 0x%02x = %s' % (raw + 1, ' '.join(cols)))
