#!/bin/bash
# Relocatable static SDK, including upstream source and port changes.
set -eu
project=$(pwd)
prefix="${PTH_PREFIX:-$HOME/opt/pth-amix}"
source="${PTH_SOURCE:-$HOME/src/upstream/pth-2.0.7}"
stage="$project/build/gnu-pth-amix-sdk"
mkdir -p "$stage/include" "$stage/lib" "$stage/share/source/tools" "$stage/examples" "$project/dist"
cp "$prefix/include/pth.h" "$prefix/include/pthread.h" "$stage/include/"
cp "$prefix/lib/libpth.a" "$prefix/lib/libpthread.a" "$stage/lib/"
cp "$source"/COPYING* "$stage/share/"
cp "$(dirname "$source")/pth-2.0.7.tar.gz" "$stage/share/source/"
cp tools/patch-gnu-pth.py tools/build-gnu-pth.sh "$stage/share/source/tools/"
# Remove only obsolete copies generated by the first packaging layout.
rm -f "$stage/share/source/patch-gnu-pth.py" "$stage/share/source/build-gnu-pth.sh"
cp tests/gnu-pth-io.c tests/gnu-pth-once.c "$stage/examples/"
cp poc/proof.c "$stage/examples/pthread-proof.c"
cp poc/LICENSE "$stage/examples/LICENSE"
cp docs/GNU-PTH.md "$stage/README.md"
: > "$stage/share/source/amix.patch"
for name in pth_mctx.c pthread.c pthread.h; do
    if diff -u --label "a/$name" --label "b/$name" \
        "$source/$name.amix-original" "$source/$name" >> "$stage/share/source/amix.patch"; then
        :
    else
        test "$?" -eq 1
    fi
done
{
    "$HOME/opt/m68k-amix/bin/m68k-elf-gcc" --version | head -n 1
    echo 'CFLAGS=-O2 -m68060 -std=gnu89 -fno-strict-aliasing'
    echo 'GNU Pth 2.0.7; static pthread emulation; mcsc/sc/mc; soft syscall mappings'
    echo 'Hardware acceptance target uname: 68060-261027-ia'
    echo 'Not a claim of full POSIX conformance or arbitrary libc I/O interception.'
} > "$stage/BUILD.txt"
(cd "$stage"; find . -type f ! -name SHA256SUMS -print0 | sort -z |
    xargs -0 sha256sum > SHA256SUMS)
tar -czf "$project/dist/gnu-pth-2.0.7-amix-m68060.tar.gz" -C "$project/build" gnu-pth-amix-sdk
sha256sum "$project/dist/gnu-pth-2.0.7-amix-m68060.tar.gz"
