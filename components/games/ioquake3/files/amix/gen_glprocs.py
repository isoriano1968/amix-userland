#!/usr/bin/env python3
"""gen_glprocs.py -- amix_glprocs.c: name -> address for every GL function
qgl.h can ask for that Mesa 3.1's static libGL.a has (GetProcAddress for a
statically linked GL).  Run from the ioq3 tree; rerun when Mesa changes."""
import os, re, subprocess
H = os.path.dirname(os.path.abspath(__file__))
qgl = open(os.path.join(H, "..", "code", "renderercommon", "qgl.h")).read()
names = set(re.findall(r"GLE\(\s*[^,]+,\s*(\w+)\s*,", qgl))
names |= {"ActiveTextureARB", "ClientActiveTextureARB", "MultiTexCoord2fARB",
          "LockArraysEXT", "UnlockArraysEXT"}
nm = subprocess.run([os.path.expanduser("~/opt/m68k-amix/bin/m68k-elf-nm"),
                     os.path.expanduser("~/Sources/usr-amix/mesa31-amix/lib/libGL.a")],
                    capture_output=True, text=True).stdout
have = set(re.findall(r" T (gl\w+)$", nm, re.M))
use = sorted(n for n in names if "gl" + n in have)
missing = sorted(n for n in names if "gl" + n not in have)
out = ["/* amix_glprocs.c -- generated by gen_glprocs.py: the GL functions qgl.h",
       "   names that Mesa 3.1's libGL.a has (%d of %d) */" % (len(use), len(names)),
       "#include <string.h>", "",
       "/* declared as plain symbols: only their addresses are wanted, and gl.h's",
       "   prototypes are not repeated here */"]
for n in use:
    out.append("extern char gl%s[];" % n)
out += ["", "static const struct { const char *name; void *fn; } procs[] = {"]
out += ['    { "gl%s", gl%s },' % (n, n) for n in use]
out += ["};", "",
        "void *amix_GetProcAddress(const char *name)",
        "{",
        "    unsigned i;",
        "    for (i = 0; i < sizeof procs / sizeof procs[0]; i++)",
        "        if (!strcmp(procs[i].name, name))",
        "            return procs[i].fn;",
        "    return 0;",
        "}", ""]
open(os.path.join(H, "amix_glprocs.c"), "w").write("\n".join(out))
print("%d procs, missing in Mesa: %s" % (len(use), " ".join(missing[:40])))
