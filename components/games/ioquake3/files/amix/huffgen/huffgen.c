/*
 * huffgen.c -- builds the message Huffman tree on the PC, once.
 *
 * MSG_initHuffman() feeds msg_hData (about 1.6 million symbols) through
 * Huff_addRef into two identical adaptive trees on every start: 27 s on the
 * A3000's 060.  The result never changes, so this program runs the same
 * code (the game's own huffman.c) on the host and writes the tree as a
 * table of indices, huffinit.h; MSG_initHuffman on AMIX only turns the
 * indices back into pointers (huffrestore.h).  huffcheck.c then checks that
 * the restored tree equals the built one, node for node.
 *
 *   sh huffgen.sh SP/code    (writes ../huffinit.h and runs huffcheck)
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "q_shared.h"
#include "qcommon.h"

/* what huffman.c needs from the engine (macros for memset/memcpy unless
   the engine's own versions are asked for) */
#ifndef Com_Memset
void Com_Memset(void *d, const int c, size_t n) { memset(d, c, n); }
void Com_Memcpy(void *d, const void *s, size_t n) { memcpy(d, s, n); }
#endif

#include HDATA

static huffman_t built;

static int ni(const huff_t *h, const node_t *p)
{
	return p ? (int)(p - h->nodeList) : -1;
}

/* a nodePtrs entry: a node (index into nodeList), or on the free list a
   pointer into nodePtrs itself (huffman.c's free_ppnode), as -2 - index */
static int ep(const huff_t *h, const node_t *p)
{
	const node_t *const *q = (const node_t *const *)p;

	if (!p)
		return -1;
	if (p >= h->nodeList && p < h->nodeList + 768)
		return (int)(p - h->nodeList);
	if (q >= (const node_t *const *)h->nodePtrs && q < (const node_t *const *)h->nodePtrs + 768)
		return -2 - (int)(q - (const node_t *const *)h->nodePtrs);
	fprintf(stderr, "huffgen: a nodePtrs entry points elsewhere\n");
	exit(1);
}

static int pi(const huff_t *h, node_t *const *p)
{
	return p ? (int)(p - h->nodePtrs) : -1;
}

static void dump(const huff_t *h)
{
	int i;

	printf("\t{\n\t\t{ %d, %d },\n", h->blocNode, h->blocPtrs);
	printf("\t\t{ %d, %d, %d, %d },\n", ni(h, h->tree), ni(h, h->lhead), ni(h, h->ltail), pi(h, h->freelist));
	printf("\t\t{");
	for (i = 0; i <= HMAX; i++)
		printf("%s%d", i % 16 ? ", " : (i ? ",\n\t\t  " : " "), ni(h, h->loc[i]));
	printf(" },\n\t\t{");
	for (i = 0; i < 768; i++)
		printf("%s%d", i % 16 ? ", " : (i ? ",\n\t\t  " : " "), ep(h, h->nodePtrs[i]));
	printf(" },\n\t\t{\n");
	for (i = 0; i < 768; i++) {
		const node_t *x = &h->nodeList[i];

		printf("\t\t\t{ %d, %d, %d, %d, %d, %d, %d, %d },\n", ni(h, x->left), ni(h, x->right),
		       ni(h, x->parent), ni(h, x->next), ni(h, x->prev), pi(h, x->head), x->weight, x->symbol);
	}
	printf("\t\t}\n\t},\n");
}

int main(void)
{
	int i, j;

	Huff_Init(&built);
	for (i = 0; i < 256; i++)
		for (j = 0; j < msg_hData[i]; j++) {
			Huff_addRef(&built.compressor, (byte)i);
			Huff_addRef(&built.decompressor, (byte)i);
		}
	printf("/* Generated by huffgen/huffgen.c from msg.c's msg_hData -- do not edit.\n"
	       " * The message Huffman trees after MSG_initHuffman (compressor, then\n"
	       " * decompressor) as indices: node fields into nodeList, head and\n"
	       " * freelist into nodePtrs, -1 = NULL. */\n");
	printf("typedef struct {\n\tint bloc[2];\t\t/* blocNode blocPtrs */\n"
	       "\tint top[4];\t\t/* tree lhead ltail freelist */\n\tshort loc[%d];\n\tshort ptrs[768];\t/* -2 - i: &nodePtrs[i] (free list) */\n"
	       "\tint nodes[768][8];\t/* left right parent next prev head weight symbol */\n} huffinit_t;\n\n", HMAX + 1);
	printf("static const huffinit_t huffinit[2] = {\n");
	dump(&built.compressor);
	dump(&built.decompressor);
	printf("};\n");
	fflush(stdout);
	return ferror(stdout) ? 1 : 0;
}
