#!/bin/sh
# build.sh -- SDL 2.30 for AMIX (68040/68060), cross-built with gcc14-cross-amix
# (m68k-elf-gcc on PATH) against X11R6.3 and gnu-pth-amix:
#   sh build.sh            -> build/install/usr/local/{lib/libSDL2.a,include/SDL2,bin/sdl2-config}
#   AMIX_SYSROOT  default ~/opt/m68k-amix-sysroot (with the shared X11R6.3 in
#                 usr/x11r6 and gnu-pth in usr/local/gnu)
#   SHM_LIBS      directory with libshmsys.a (the shared libXext has XShm)
#   PTH_LIB       gnu-pth's libraries for sdl2-config-cross (default $G/lib)
#   AMIX_GATE     amix-gate (default beside amix-userland): core 1's zzgl.h and
#                 bench.h for the zzhdmi audio driver
# The source: SDL2-2.30.12/ (fetch.sh), copied to build/, patches/ applied and
# amix/ laid over it.
set -e
H=$(cd "$(dirname "$0")" && pwd)
V=2.30.12
SR=${AMIX_SYSROOT:-$HOME/opt/m68k-amix-sysroot}
X=$SR/usr/x11r6
G=$SR/usr/local/gnu
B=$H/build/SDL2-$V
O=$H/build/obj
P=$H/build/install/usr/local
C1=${AMIX_GATE:-$H/../../../../amix-gate}/usr/src/firmware/core1
[ -d "$H/SDL2-$V" ] || { echo "no SDL2-$V/: run fetch.sh"; exit 1; }
[ -f "$G/include/pthread.h" ] || { echo "no gnu-pth in $G"; exit 1; }
[ -f "$C1/zzgl/zzgl.h" ] || { echo "no amix-gate's core 1 headers in $C1"; exit 1; }

rm -rf "$B" "$O"
mkdir -p "$H/build" "$O" "$P/lib" "$P/include/SDL2" "$P/bin"
cp -a "$H/SDL2-$V" "$B"
for p in "$H"/patches/*.patch; do
	patch -s -d "$B" -p1 < "$p"
done
cp -a "$H/amix/src/." "$B/src/"
python3 "$H/amix/mkconfig.py" "$B/include/SDL_config.h.cmake" > "$B/include/SDL_config.h"

# gnu-pth has no POSIX semaphores: SDL's generic ones (mutex + condition).
# every file sees gnu-pth's pthread.h: read, write, select, poll and the sleeps
# become calls that let the other threads run
CF="-O2 -m68060 -fno-strict-aliasing -D_REENTRANT -DUSING_GENERATED_CONFIG_H
	-I$B/include -I$B/src -I$G/include -include $G/include/pthread.h -include $H/amix/include/SDL_amix.h
	-I$X/include
	-Wno-implicit-int -Wno-error=incompatible-pointer-types -Wno-deprecated-declarations"
cd "$B/src"
SRCS=$(ls *.c atomic/*.c audio/*.c audio/dummy/*.c audio/amix/*.c audio/zzhdmi/*.c cpuinfo/*.c \
	events/*.c file/*.c filesystem/unix/*.c haptic/*.c joystick/*.c libm/*.c \
	locale/*.c locale/dummy/*.c misc/*.c misc/dummy/*.c power/*.c render/*.c \
	render/software/*.c render/zz9k/*.c sensor/*.c stdlib/*.c thread/*.c \
	thread/pthread/SDL_systhread.c thread/pthread/SDL_sysmutex.c thread/pthread/SDL_syscond.c \
	thread/pthread/SDL_systls.c thread/generic/SDL_syssem.c core/amix/*.c \
	timer/*.c timer/unix/*.c video/*.c video/dummy/*.c video/x11/*.c video/yuv2rgb/*.c \
	core/unix/SDL_poll.c dynapi/*.c 2>/dev/null)
fail=0
for f in $SRCS; do
	o=$O/$(echo "$f" | tr / _ | sed 's/\.c$/.o/')
	case $f in audio/zzhdmi/*) XF="-I$C1/zzgl -I$C1/cores/h264bench" ;; *) XF= ;; esac
	m68k-elf-gcc $CF $XF -c "$f" -o "$o" 2> "$o.log" || { echo "FAIL $f"; sed -n 1,12p "$o.log"; fail=1; }
done
[ $fail = 0 ] || exit 1
rm -f "$P/lib/libSDL2.a"
m68k-elf-ar rc "$P/lib/libSDL2.a" "$O"/*.o
m68k-elf-ranlib "$P/lib/libSDL2.a"
cp "$B"/include/*.h "$P/include/SDL2/"
sed -e "s|@prefix@|/usr/local|; s|@exec_prefix@|\${prefix}|; s|@bindir@|\${exec_prefix}/bin|;
	s|@libdir@|\${exec_prefix}/lib|; s|@includedir@|\${prefix}/include|; s|@SDL_VERSION@|$V|;
	s|@SDL_CFLAGS@|-I\${includedir}/SDL2 -D_REENTRANT|;
	s|@SDL_LIBS@|-L\${libdir} -lSDL2|;
	s|@SDL_STATIC_LIBS@|-lXext -lX11 -lshmsys -lsocket -lnsl -lpthread -lpth -lm|;
	s|@ENABLE_STATIC_TRUE@||; s|@ENABLE_STATIC_FALSE@|#|; s|@ENABLE_SHARED_TRUE@|#|; s|@ENABLE_SHARED_FALSE@||" \
	"$B/sdl2-config.in" > "$P/bin/sdl2-config"
chmod 755 "$P/bin/sdl2-config"
# for cross-building against this tree (FFmpeg's configure, ...): -lSDL2 and
# its static dependencies, as -L/-l so that they come after the objects
# the shared X libraries first: SHM_LIBS may also hold an old static libXext.a
SL="-L$X/lib -Wl,-rpath,/usr/x11r6/lib -L${PTH_LIB:-$G/lib}${SHM_LIBS:+ -L$SHM_LIBS}"
cat > "$H/build/sdl2-config-cross" <<EOS
#!/bin/sh
# sdl2-config for cross-building against sdl2-amix (generated by build.sh)
for a in "\$@"; do
	case \$a in
	--version) echo $V ;;
	--prefix|--exec-prefix) echo $P ;;
	--cflags) echo -I$P/include/SDL2 -D_REENTRANT ;;
	--libs|--static-libs) echo -L$P/lib -lSDL2 $SL -lXext -lX11 -lshmsys -lsocket -lnsl -lpthread -lpth -lm ;;
	*) echo "usage: \$0 [--version] [--cflags] [--libs] [--static-libs]" >&2; exit 1 ;;
	esac
done
EOS
chmod 755 "$H/build/sdl2-config-cross"
ls -l "$P/lib/libSDL2.a"
