#!/usr/bin/env python3
"""js2c.py NAME IN.js OUT.h -- a built-in's JavaScript source as a C string
(const char NAME[]), for big-endian machines, where QuickJS cannot read the
little-endian bytecode in builtin-*.h (patch 0002)."""
import sys

name, src, out = sys.argv[1:4]
data = open(src, "rb").read()
with open(out, "w") as f:
    f.write("/* generated by js2c.py from %s */\n" % src.split("/")[-1])
    f.write("const char %s[] =\n" % name)
    for line in data.split(b"\n"):
        s = "".join(c if 32 <= ord(c) < 127 and c not in '"\\?' else "\\%03o" % ord(c)
                    for c in (line + b"\n").decode("latin-1"))
        f.write('    "%s"\n' % s)
    f.write(";\n")
