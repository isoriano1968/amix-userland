#!/usr/bin/env python3
"""amix-cxxfix.py -- C++-usable copies of AMIX's K&R function declarations.

AMIX's 1991 headers declare much of libc, libnsl and RPC without parameter
lists:  extern bool_t xdr_int();   struct hostent *gethostbyname();
In C that means "any arguments"; in C++ it means "no arguments", so every
call from C++ fails ("too many arguments to function").  This writes copies
of the affected headers in which each such empty parameter list -- in a
declaration or a function-pointer type -- becomes "(...)".

That is ABI-neutral on m68k: the headers are extern "C" (C++ wraps system
headers), and a call through a "(...)" declaration passes its arguments on
the stack with the default promotions, exactly as a K&R call does.

Where gcc14-cross-amix already has a repaired header in include-fixed, that
version is the input.  Output goes to OUT/, which the C++ compile searches
with -isystem, before include-fixed and the sysroot.  The output contains
AMIX's own header text: it is generated, never committed.

Usage: amix-cxxfix.py SYSROOT INCLUDE_FIXED OUT
"""
import os
import re
import sys

sysroot, fixed, out = sys.argv[1:4]
inc = os.path.join(sysroot, "usr/include")

# name() where name is an identifier (or (*name)() / (*name[])()), not a
# macro call: only in declarations, i.e. the "()" closes a declarator and is
# followed by ';' ',' ')' or another declarator piece.
# The parameter list may be empty or hold only a comment naming the
# parameters, as AMIX's RPC headers do: clnt_create(/*host, prog, vers*/);
DECL = re.compile(r"(\b[A-Za-z_]\w*\s*|\(\s*\*\s*[A-Za-z_]\w*\s*(?:\[[^\]]*\])?\s*\)\s*)\(\s*(?:/\*.*?\*/\s*)*\)(?=\s*[;,)])")


# size_t: AMIX's headers say "unsigned int", gcc 14 for m68k-elf says
# "unsigned long" (__SIZE_TYPE__).  Same width, but C++ mangles them
# differently, and which typedef a translation unit meets first varies --
# so _Tt_api_stg_stack::malloc(size_t) was defined as (unsigned long) and
# called as (unsigned int).  The compiler's type wins: libstdc++ and
# operator new are built with it.
SIZE_T = re.compile(r"^(\s*typedef\s+)(?:unsigned\s+int|unsigned|uint_t)(\s+size_t\s*;)")


def convert(text):
    out_lines, n = [], 0
    in_define = False
    for line in text.split("\n"):
        stripped = line.lstrip()
        directive = stripped.startswith("#") or in_define
        in_define = directive and line.rstrip().endswith("\\")
        if not directive and SIZE_T.match(line):
            out_lines.append(SIZE_T.sub(r"\1__SIZE_TYPE__\2", line))
            n += 1
            continue
        if directive or not re.search(r"\(\s*(?:/\*.*?\*/\s*)*\)", line):
            out_lines.append(line)
            continue
        # statements (in the few static inline functions some headers carry)
        # are left alone: there "f()" is a call, and "f(...)" no syntax
        if re.match(r"\s*(return|if|while|for|switch|do|else)\b", line) or "=" in line:
            out_lines.append(line)
            continue
        new, k = DECL.subn(lambda m: m.group(1) + "(...)", line)
        out_lines.append(new)
        n += k
    return "\n".join(out_lines), n


total_files = total = 0
for root, dirs, files in os.walk(inc):
    for f in files:
        if not f.endswith(".h"):
            continue
        rel = os.path.relpath(os.path.join(root, f), inc)
        # include-fixed holds two kinds of file: real repairs (K&R inline
        # functions rewritten) and linkage wrappers that #include_next the
        # vendor header.  A repair is the input; for a wrapper the vendor
        # header is, and the copy gets the extern "C" the wrapper provided.
        src = os.path.join(fixed, rel)
        # (a directive, not a comment that mentions one: the fixed
        # <sys/types.h> explains why it is NOT a wrapper)
        if not os.path.isfile(src) or re.search(r"^\s*#\s*include_next", open(src, encoding="latin-1").read(), re.M):
            src = os.path.join(inc, rel)
        try:
            text = open(src, encoding="latin-1").read()
        except (IsADirectoryError, FileNotFoundError):
            continue
        new, n = convert(text)
        if n == 0:
            continue
        guard = "AMIX_CXXFIX_" + re.sub(r"\W", "_", rel).upper()
        new = ("/* generated by amix-cxxfix.py from AMIX's <%s>: K&R \"()\" -> \"(...)\" for C++ */\n"
               "#ifndef %s\n#define %s\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n%s\n"
               "#ifdef __cplusplus\n}\n#endif\n#endif\n") % (rel, guard, guard, new)
        dst = os.path.join(out, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        open(dst, "w", encoding="latin-1").write(new)
        total_files += 1
        total += n
# <osfcn.h> is cfront's "OS functions" header, with prototypes of its own
# (execv(const char*, const char**), wait(), ...) that contradict
# <unistd.h> and <sys/wait.h>.  For gcc 14 it is just those headers.
open(os.path.join(out, "osfcn.h"), "w").write(
    "/* generated by amix-cxxfix.py: cfront's <osfcn.h> for gcc 14 --\n"
    " * the system headers it summarised, not its own (contradicting) prototypes */\n"
    "#ifndef AMIX_CXXFIX_OSFCN_H\n#define AMIX_CXXFIX_OSFCN_H\n"
    "#include <sys/types.h>\n#include <unistd.h>\n#include <stdlib.h>\n#include <sys/wait.h>\n"
    "#endif\n")
total_files += 1
print(f"amix-cxxfix: {total} declarations in {total_files} headers -> {out}")
